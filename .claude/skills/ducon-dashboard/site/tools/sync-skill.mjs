// Builds the portable bundle served at /api/skill: the /ducon-dashboard skill (SKILL.md + references)
// plus the site source, so a second PC can install the skill and edit the dashboard.
// Writes functions/lib/skill.js. Run `npm run skill:sync` after changing the skill or the site, then deploy.
// Secrets never go in the bundle: the script stops if any value from .dev.vars or ducon-desk.env appears in a file.
import {readFileSync, writeFileSync, mkdirSync, statSync, readdirSync, existsSync} from 'node:fs';
import {homedir} from 'node:os';
import {join, dirname, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillDir = join(homedir(), '.claude', 'skills', 'ducon-dashboard');
const out = join(root, 'functions', 'lib', 'skill.js');
const read = (p) => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');

const files = [];
const addSkill = (rel, full) => files.push({path: 'ducon-dashboard/' + rel, text: read(full)});
addSkill('SKILL.md', join(skillDir, 'SKILL.md'));
const refDir = join(skillDir, 'references');
if (existsSync(refDir)) {
  for (const f of readdirSync(refDir).sort()) {
    if (f.endsWith('.md')) addSkill('references/' + f, join(refDir, f));
  }
}

const SITE = [
  'public/index.html',
  'functions/api/[[path]].js',
  'tools/desk.mjs',
  'tools/pull-live.mjs',
  'tools/pull-source.mjs',
  'tools/sync-skill.mjs',
  'package.json',
  'package-lock.json',
  'wrangler.toml',
  'schema.sql',
  'README.md',
  '.gitignore',
  '.claude/launch.json'
];
for (const rel of SITE) {
  const full = join(root, ...rel.split('/'));
  if (!existsSync(full)) throw new Error('missing site file: ' + rel);
  files.push({path: 'ducon-dashboard/site/' + rel, text: read(full)});
}

// Secret guard: every value in the local secret files must be absent from the bundle.
const secretFiles = [join(root, '.dev.vars'), join(homedir(), '.claude', 'ducon-desk.env')];
const secrets = [];
for (const f of secretFiles) {
  if (!existsSync(f)) continue;
  for (const line of read(f).split('\n')) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.+?)\s*$/.exec(line);
    const isSecret = /KEY|SECRET|TOKEN|PASS|CODE/i.test(m ? m[1] : '') && !/URL/i.test(m ? m[1] : '');
    if (m && isSecret && m[2].replace(/^["']|["']$/g, '').length >= 8) secrets.push({name: m[1], value: m[2].replace(/^["']|["']$/g, '')});
  }
}
const bundleText = files.map((f) => f.text).join('\n');
for (const s of secrets) {
  if (bundleText.includes(s.value)) throw new Error('Secret ' + s.name + ' found in the bundle. Not written. Remove it from the source first.');
}

const updated = new Date().toISOString().slice(0, 10);
const skillText = files[0].text;
mkdirSync(dirname(out), {recursive: true});
writeFileSync(out, '// Generated by tools/sync-skill.mjs. Do not edit by hand.\nexport const SKILL = ' + JSON.stringify({updated, text: skillText, files}) + ';\n');
console.log('bundle written:', files.length, 'files,', bundleText.length, 'characters, secrets checked:', secrets.length);
