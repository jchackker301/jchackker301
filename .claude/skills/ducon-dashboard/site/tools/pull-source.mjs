#!/usr/bin/env node
// Writes the site source and the skill files from the live bundle, so any PC starts from what is deployed.
//   node tools/pull-source.mjs <target-folder>
// Needs DESK_URL and DESK_KEY (see ~/.claude/ducon-desk.env). Writes <target>/site/... and <target>/ducon-dashboard/...
// Never writes secrets: the bundle contains none, and .dev.vars is not part of it.
import {mkdirSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';

const base = (process.env.DESK_URL || '').replace(/\/$/, '');
const key = process.env.DESK_KEY || '';
const target = process.argv[2];
if (!base || !key || !target) {
  console.error('Usage: DESK_URL and DESK_KEY must be set. Run: node tools/pull-source.mjs <target-folder>');
  process.exit(2);
}

const res = await fetch(base + '/api/agent/skill', {headers: {authorization: 'Bearer ' + key}});
if (!res.ok) {
  console.error('Request failed:', res.status, await res.text());
  process.exit(1);
}
const data = await res.json();
if (!Array.isArray(data.files) || !data.files.length) {
  console.error('The live site has no bundle yet. Deploy once with npm run deploy.');
  process.exit(1);
}

// Site source goes to <target>/site/..., the skill goes to <target>/ducon-dashboard/... (the same layout as the zip).
const root = resolve(target);
for (const f of data.files) {
  if (f.path.includes('..')) throw new Error('Unsafe path in bundle: ' + f.path);
  const rel = f.path.startsWith('ducon-dashboard/site/') ? f.path.slice('ducon-dashboard/'.length) : f.path;
  const full = join(root, ...rel.split('/'));
  mkdirSync(dirname(full), {recursive: true});
  writeFileSync(full, f.text, 'utf8');
}
// The API imports functions/lib/skill.js, which the bundle leaves out (it contains the bundle itself).
// Rebuild it here from the same data, so the site builds straight after the pull.
const libFile = join(root, 'site', 'functions', 'lib', 'skill.js');
mkdirSync(dirname(libFile), {recursive: true});
writeFileSync(libFile, '// Generated by tools/sync-skill.mjs. Do not edit by hand.\nexport const SKILL = ' + JSON.stringify({updated: data.updated, text: data.text, files: data.files}) + ';\n', 'utf8');
console.log('wrote', data.files.length, 'files into', root, '(site/ and ducon-dashboard/, bundle date', data.updated + ')');
